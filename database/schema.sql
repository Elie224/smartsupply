-- ---------------------------------------------------------------------
-- 12) ml.feature_snapshots : une ligne = un produit observé à la fin du jour as_of_date.
--     Toutes les variables n'utilisent QUE des informations connues à as_of_date.
--     La cible (demande J+1..J+7) reste NULL tant que ces 7 jours ne sont pas passés.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS ml.feature_snapshots (
    as_of_date                      DATE              NOT NULL,
    product_id                      BIGINT            NOT NULL REFERENCES raw.products (product_id),
    category                        TEXT              NOT NULL,
    supplier_id                     BIGINT            NOT NULL,
    -- historique de la demande (unités demandées)
    demand_lag_1                    INTEGER           NOT NULL,   -- demande du jour D
    demand_lag_7                    INTEGER           NOT NULL,   -- demande du jour D-6
    demand_lag_14                   INTEGER           NOT NULL,   -- demande du jour D-13
    demand_lag_28                   INTEGER           NOT NULL,   -- demande du jour D-27
    demand_rolling_mean_7           DOUBLE PRECISION  NOT NULL,
    demand_rolling_mean_28          DOUBLE PRECISION  NOT NULL,
    demand_rolling_std_28           DOUBLE PRECISION  NOT NULL,
    lost_sales_rolling_7            INTEGER           NOT NULL,   -- ruptures récentes
    -- prix et promotions CONNUES à D (annoncées au plus tard à D)
    price_as_of                     NUMERIC(12,2)     NOT NULL,
    promotion_active                BOOLEAN           NOT NULL,
    discount_pct                    DOUBLE PRECISION  NOT NULL,
    promo_days_next_7               INTEGER           NOT NULL,
    promo_max_discount_next_7       DOUBLE PRECISION  NOT NULL,
    -- calendrier
    weekday                         SMALLINT          NOT NULL,   -- 0 = lundi
    month                           SMALLINT          NOT NULL,
    day_of_year                     SMALLINT          NOT NULL,
    is_weekend                      BOOLEAN           NOT NULL,
    -- stock et approvisionnement CONNUS à D
    stock_as_of                     INTEGER           NOT NULL,
    incoming_qty_known_as_of        INTEGER           NOT NULL,   -- en transit, attendu d'ici D+7
    supplier_lead_time_known_as_of  INTEGER           NOT NULL,
    -- cible
    target_demand_next_7d           INTEGER,
    built_at                        TIMESTAMPTZ       NOT NULL DEFAULT now(),

    PRIMARY KEY (as_of_date, product_id)
);

