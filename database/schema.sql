-- =====================================================================
-- SmartSupply AI - Schéma de base (Phase 1)
-- Exécutable plusieurs fois sans erreur (IF NOT EXISTS) = idempotent.
-- Conventions :
--   * Devise unique : EUR, montants en NUMERIC(12,2) (jamais de FLOAT pour l'argent).
--   * Dates en TIMESTAMPTZ (avec fuseau) pour éviter les ambiguïtés.
--   * Deux horloges : created_at = date métier simulée,
--                     ingested_at = instant réel d'insertion en base.
-- =====================================================================

BEGIN;

-- ---------------------------------------------------------------------
-- 1) Schémas : séparation des responsabilités
-- ---------------------------------------------------------------------
CREATE SCHEMA IF NOT EXISTS raw;        -- données brutes écrites par le simulateur
CREATE SCHEMA IF NOT EXISTS analytics;  -- vues lues par Power BI
CREATE SCHEMA IF NOT EXISTS ml;         -- features, prévisions, évaluations

-- ---------------------------------------------------------------------
-- 2) raw.suppliers : fournisseurs
--    Créée en premier car raw.products y fait référence.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS raw.suppliers (
    supplier_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name               TEXT          NOT NULL,
    country            TEXT          NOT NULL,
    lead_time_days     INTEGER       NOT NULL,   -- délai annoncé de livraison
    reliability_score  NUMERIC(4,3)  NOT NULL,   -- 0.000 = jamais à l'heure, 1.000 = toujours
    ingested_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT chk_suppliers_lead_time   CHECK (lead_time_days BETWEEN 1 AND 120),
    CONSTRAINT chk_suppliers_reliability CHECK (reliability_score BETWEEN 0 AND 1)
);

-- ---------------------------------------------------------------------
-- 3) raw.products : catalogue
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS raw.products (
    product_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku          TEXT           NOT NULL,
    name         TEXT           NOT NULL,
    category     TEXT           NOT NULL,
    unit_cost    NUMERIC(12,2)  NOT NULL,   -- prix d'achat (EUR)
    unit_price   NUMERIC(12,2)  NOT NULL,   -- prix de vente catalogue (EUR)
    supplier_id  BIGINT         NOT NULL,
    created_at   TIMESTAMPTZ    NOT NULL,   -- date de lancement simulée
    active       BOOLEAN        NOT NULL DEFAULT TRUE,
    ingested_at  TIMESTAMPTZ    NOT NULL DEFAULT now(),

    CONSTRAINT uq_products_sku        UNIQUE (sku),
    CONSTRAINT chk_products_cost      CHECK (unit_cost > 0),
    -- Prix catalogue >= coût : pas de marge négative "normale".
    -- Les promotions seront gérées à part (raw.promotions).
    CONSTRAINT chk_products_price     CHECK (unit_price >= unit_cost),
    -- RESTRICT : impossible de supprimer un fournisseur qui a encore des produits.
    CONSTRAINT fk_products_supplier   FOREIGN KEY (supplier_id)
        REFERENCES raw.suppliers (supplier_id) ON DELETE RESTRICT
);

-- PostgreSQL n'indexe PAS automatiquement les clés étrangères :
-- on l'ajoute pour accélérer les jointures produits <-> fournisseurs.
CREATE INDEX IF NOT EXISTS idx_products_supplier ON raw.products (supplier_id);
CREATE INDEX IF NOT EXISTS idx_products_category ON raw.products (category);

-- ---------------------------------------------------------------------
-- 4) raw.clients : clients B2B / B2C
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS raw.clients (
    client_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         TEXT         NOT NULL,
    segment      TEXT         NOT NULL,
    city         TEXT         NOT NULL,
    created_at   TIMESTAMPTZ  NOT NULL,   -- date d'inscription simulée
    ingested_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT chk_clients_segment CHECK (segment IN ('B2B', 'B2C'))
);

-- ---------------------------------------------------------------------
-- 5) raw.warehouses : entrepôts
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS raw.warehouses (
    warehouse_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          TEXT         NOT NULL,
    city          TEXT         NOT NULL,
    capacity      INTEGER      NOT NULL,   -- capacité en unités stockables
    ingested_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uq_warehouses_name    UNIQUE (name),
    CONSTRAINT chk_warehouses_capacity CHECK (capacity > 0)
);

-- =====================================================================
-- PHASE 2 : activité simulée
-- =====================================================================

-- ---------------------------------------------------------------------
-- 6) raw.simulation_runs : un enregistrement par jour simulé.
--    UNIQUE(simulated_date) = garantie qu'un jour n'est jamais simulé deux fois,
--    même si le générateur est relancé après une coupure.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS raw.simulation_runs (
    run_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seed            INTEGER      NOT NULL,
    mode            TEXT         NOT NULL,
    simulated_date  DATE         NOT NULL,
    started_at      TIMESTAMPTZ  NOT NULL,
    finished_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    status          TEXT         NOT NULL DEFAULT 'success',

    CONSTRAINT uq_simulation_runs_date   UNIQUE (simulated_date),
        CONSTRAINT chk_simulation_runs_status CHECK (status IN ('success', 'failed'))
);
-- Contrainte recréée à chaque exécution : permet d'ajouter un mode sans tout reconstruire.
ALTER TABLE raw.simulation_runs DROP CONSTRAINT IF EXISTS chk_simulation_runs_mode;
ALTER TABLE raw.simulation_runs ADD CONSTRAINT chk_simulation_runs_mode
    CHECK (mode IN ('bootstrap', 'once', 'stream', 'pipeline', 'scenario'));

-- ---------------------------------------------------------------------
-- 7) raw.promotions
--    announced_at = jour où la promo devient connue. Servira à l'anti-fuite :
--    une feature à la date D ne pourra utiliser que les promos annoncées <= D.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS raw.promotions (
    promotion_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id    BIGINT        NOT NULL REFERENCES raw.products (product_id),
    starts_at     DATE          NOT NULL,
    ends_at       DATE          NOT NULL,
    discount_pct  NUMERIC(4,3)  NOT NULL,
    announced_at  DATE          NOT NULL,
    ingested_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT chk_promotions_dates     CHECK (ends_at >= starts_at),
    CONSTRAINT chk_promotions_announce  CHECK (announced_at <= starts_at),
    CONSTRAINT chk_promotions_discount  CHECK (discount_pct > 0 AND discount_pct <= 0.7)
);
CREATE INDEX IF NOT EXISTS idx_promotions_product ON raw.promotions (product_id, starts_at);

-- ---------------------------------------------------------------------
-- 8) raw.orders / raw.order_items : la demande des clients
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS raw.orders (
    order_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id    BIGINT       NOT NULL REFERENCES raw.clients (client_id),
    ordered_at   TIMESTAMPTZ  NOT NULL,
    status       TEXT         NOT NULL,
    channel      TEXT         NOT NULL,
    ingested_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT chk_orders_status  CHECK (status IN ('fulfilled', 'partial', 'unfulfilled')),
    CONSTRAINT chk_orders_channel CHECK (channel IN ('web', 'store', 'b2b_portal'))
);
CREATE INDEX IF NOT EXISTS idx_orders_ordered_at ON raw.orders (ordered_at);
CREATE INDEX IF NOT EXISTS idx_orders_client     ON raw.orders (client_id);

CREATE TABLE IF NOT EXISTS raw.order_items (
    order_item_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        BIGINT         NOT NULL REFERENCES raw.orders (order_id),
    product_id      BIGINT         NOT NULL REFERENCES raw.products (product_id),
    warehouse_id    BIGINT         NOT NULL REFERENCES raw.warehouses (warehouse_id),
    requested_qty   INTEGER        NOT NULL,   -- DEMANDE (cible du ML)
    fulfilled_qty   INTEGER        NOT NULL,   -- VENTE réellement servie
    lost_sales_qty  INTEGER        NOT NULL,   -- demande perdue (rupture)
    unit_price      NUMERIC(12,2)  NOT NULL,   -- prix payé, promo incluse (EUR)
    ingested_at     TIMESTAMPTZ    NOT NULL DEFAULT now(),

    CONSTRAINT chk_order_items_requested CHECK (requested_qty > 0),
    CONSTRAINT chk_order_items_fulfilled CHECK (fulfilled_qty BETWEEN 0 AND requested_qty),
    CONSTRAINT chk_order_items_lost      CHECK (lost_sales_qty = requested_qty - fulfilled_qty),
    CONSTRAINT chk_order_items_price     CHECK (unit_price > 0)
);
CREATE INDEX IF NOT EXISTS idx_order_items_order   ON raw.order_items (order_id);
CREATE INDEX IF NOT EXISTS idx_order_items_product ON raw.order_items (product_id, warehouse_id);

-- ---------------------------------------------------------------------
-- 9) raw.purchase_orders / raw.purchase_order_items : réapprovisionnements
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS raw.purchase_orders (
    po_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id   BIGINT       NOT NULL REFERENCES raw.suppliers (supplier_id),
    warehouse_id  BIGINT       NOT NULL REFERENCES raw.warehouses (warehouse_id),
    ordered_at    DATE         NOT NULL,
    expected_at   DATE         NOT NULL,   -- date promise (délai fournisseur)
    received_at   DATE,                    -- date réelle, NULL tant que non reçue
    status        TEXT         NOT NULL,
    ingested_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT chk_po_status   CHECK (status IN ('in_transit', 'received')),
    CONSTRAINT chk_po_expected CHECK (expected_at > ordered_at),
    CONSTRAINT chk_po_received CHECK (received_at IS NULL OR received_at > ordered_at),
    -- "reçue" <=> une date de réception existe
    CONSTRAINT chk_po_status_received CHECK ((status = 'received') = (received_at IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS idx_po_status ON raw.purchase_orders (status);

CREATE TABLE IF NOT EXISTS raw.purchase_order_items (
    po_item_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    po_id         BIGINT         NOT NULL REFERENCES raw.purchase_orders (po_id),
    product_id    BIGINT         NOT NULL REFERENCES raw.products (product_id),
    ordered_qty   INTEGER        NOT NULL,
    received_qty  INTEGER,
    unit_cost     NUMERIC(12,2)  NOT NULL,
    ingested_at   TIMESTAMPTZ    NOT NULL DEFAULT now(),

    CONSTRAINT chk_po_items_ordered  CHECK (ordered_qty > 0),
    CONSTRAINT chk_po_items_received CHECK (received_qty IS NULL OR received_qty BETWEEN 0 AND ordered_qty),
    CONSTRAINT chk_po_items_cost     CHECK (unit_cost > 0)
);
CREATE INDEX IF NOT EXISTS idx_po_items_po ON raw.purchase_order_items (po_id);

-- ---------------------------------------------------------------------
-- 10) raw.stock_movements : journal APPEND-ONLY de toutes les entrées/sorties
--     Le stock d'un produit = somme de ses quantity_delta.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS raw.stock_movements (
    movement_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_time      TIMESTAMPTZ  NOT NULL,   -- horloge métier simulée
    product_id      BIGINT       NOT NULL REFERENCES raw.products (product_id),
    warehouse_id    BIGINT       NOT NULL REFERENCES raw.warehouses (warehouse_id),
    movement_type   TEXT         NOT NULL,
    quantity_delta  INTEGER      NOT NULL,
    source_id       BIGINT,                  -- order_item_id ou po_item_id selon le type
    ingested_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),   -- horloge réelle

    CONSTRAINT chk_movements_type CHECK (movement_type IN ('initial', 'receipt', 'sale')),
    -- Les ventes sortent du stock (négatif), le reste en ajoute (positif).
    CONSTRAINT chk_movements_sign CHECK (
        (movement_type = 'sale' AND quantity_delta < 0)
        OR (movement_type IN ('initial', 'receipt') AND quantity_delta > 0)
    )
);
CREATE INDEX IF NOT EXISTS idx_movements_product_time
    ON raw.stock_movements (product_id, warehouse_id, event_time);

-- Interdit UPDATE et DELETE : on corrige une erreur par un nouveau mouvement,
-- jamais en réécrivant l'historique.
CREATE OR REPLACE FUNCTION raw.forbid_modification() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'La table % est en ajout seul (append-only)', TG_TABLE_NAME;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_stock_movements_append_only ON raw.stock_movements;
CREATE TRIGGER trg_stock_movements_append_only
    BEFORE UPDATE OR DELETE ON raw.stock_movements
    FOR EACH ROW EXECUTE FUNCTION raw.forbid_modification();

-- ---------------------------------------------------------------------
-- 11) raw.inventory_balances : solde courant (= somme du journal)
--     Matérialisé pour éviter de resommer tout le journal à chaque lecture.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS raw.inventory_balances (
    product_id    BIGINT       NOT NULL REFERENCES raw.products (product_id),
    warehouse_id  BIGINT       NOT NULL REFERENCES raw.warehouses (warehouse_id),
    on_hand_qty   INTEGER      NOT NULL,
    updated_at    TIMESTAMPTZ  NOT NULL,   -- horloge simulée

    PRIMARY KEY (product_id, warehouse_id),
    CONSTRAINT chk_balances_non_negative CHECK (on_hand_qty >= 0)
