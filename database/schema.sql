-- ---------------------------------------------------------------------
-- 14) ml.model_runs : un entraînement nocturne = une ligne (registre des modèles)
--     Le modèle EN PLACE = le dernier entraînement mis en service (promoted).
--     Le modèle lui-même est stocké dans la base (model_blob) : il est disponible
--     aussi bien pour le pipeline Docker que pour les commandes lancées sur le PC.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS ml.model_runs (
    run_id           TEXT              PRIMARY KEY,          -- horodatage UTC de l'entraînement
    trained_at       TIMESTAMPTZ       NOT NULL DEFAULT now(),
    model_name       TEXT              NOT NULL,
    data_until       DATE              NOT NULL UNIQUE,      -- dernière date avec cible connue
    eval_start       DATE              NOT NULL,             -- fenêtre d'évaluation (8 semaines)
    eval_end         DATE              NOT NULL,
    n_train_rows     INTEGER           NOT NULL,
    wape             DOUBLE PRECISION  NOT NULL,             -- scores du nouveau modèle sur la fenêtre
    mae              DOUBLE PRECISION  NOT NULL,
    bias             DOUBLE PRECISION  NOT NULL,
    baseline_wape    DOUBLE PRECISION  NOT NULL,             -- méthode naïve 28 j, même fenêtre
    champion_run_id  TEXT,                                   -- modèle en place au moment de la décision
    champion_wape    DOUBLE PRECISION,
    promoted         BOOLEAN           NOT NULL,
    decision         TEXT              NOT NULL,             -- raison, en clair
    model_blob       BYTEA,                                  -- modèle sérialisé (seulement s'il est retenu)
    CONSTRAINT chk_model_runs_blob CHECK (NOT promoted OR model_blob IS NOT NULL)
);
-- Réglages LightGBM utilisés (affichés dans MLflow). Vide pour les entraînements
-- antérieurs à cette colonne.
ALTER TABLE ml.model_runs ADD COLUMN IF NOT EXISTS params JSONB;

-- ---------------------------------------------------------------------
-- 15) ml.forecasts : prévisions faites chaque nuit, JAMAIS modifiées ensuite
--     as_of_date = dernière journée connue ; la prévision couvre les 7 jours suivants.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS ml.forecasts (
    as_of_date     DATE         NOT NULL,
    product_id     BIGINT       NOT NULL REFERENCES raw.products (product_id),
    horizon_start  DATE         NOT NULL,
    horizon_end    DATE         NOT NULL,
    predicted_qty  INTEGER      NOT NULL CHECK (predicted_qty >= 0),
    run_id         TEXT         NOT NULL REFERENCES ml.model_runs (run_id),
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    PRIMARY KEY (as_of_date, product_id),
    CONSTRAINT chk_forecasts_horizon CHECK (horizon_start = as_of_date + 1 AND horizon_end = as_of_date + 7)
);

-- ---------------------------------------------------------------------
-- 15 bis) Surveillance du modèle en service (une ligne par journée)
--   ml.drift_metrics   : dérive de chaque variable (PSI) entre la période
--                        d'entraînement du modèle (1 an) et les 28 derniers jours ;
--   ml.monitoring_daily: résumé du jour (dérive) + erreur RÉELLE de la prévision
--                        faite ce jour-là, connue 7 jours plus tard.
--   Les colonnes *_logged indiquent ce qui a déjà été recopié dans MLflow.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS ml.drift_metrics (
    as_of_date       DATE              NOT NULL,
    feature          TEXT              NOT NULL,
    psi              DOUBLE PRECISION  NOT NULL CHECK (psi >= 0),
    level            TEXT              NOT NULL CHECK (level IN ('stable', 'à surveiller', 'forte')),
    reference_start  DATE              NOT NULL,
    reference_end    DATE              NOT NULL,
    current_start    DATE              NOT NULL,
    model_run_id     TEXT              NOT NULL REFERENCES ml.model_runs (run_id),
    computed_at      TIMESTAMPTZ       NOT NULL DEFAULT now(),
    PRIMARY KEY (as_of_date, feature)
);

CREATE TABLE IF NOT EXISTS ml.monitoring_daily (
    as_of_date      DATE              PRIMARY KEY,
    model_run_id    TEXT              REFERENCES ml.model_runs (run_id),
    max_psi         DOUBLE PRECISION,
    top_feature     TEXT,
    n_watch         INTEGER,          -- variables « à surveiller » (PSI 0,1 à 0,25)
    n_strong        INTEGER,          -- variables en dérive forte (PSI > 0,25)
    drift_logged    BOOLEAN           NOT NULL DEFAULT false,
    real_wape       DOUBLE PRECISION, -- erreur réelle de la prévision de ce jour (7 jours après)
    real_bias       DOUBLE PRECISION,
    real_logged     BOOLEAN           NOT NULL DEFAULT false,
    updated_at      TIMESTAMPTZ       NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- 16) ops.pipeline_runs : journal du cycle automatique (un passage = une ligne)
--     Sert à savoir, sans ouvrir Prefect, si le cycle tourne bien :
--     vue analytics.v_pipeline_health (Power BI) et alerte Windows (smartsupply.health).
-- ---------------------------------------------------------------------
CREATE SCHEMA IF NOT EXISTS ops;

CREATE TABLE IF NOT EXISTS ops.pipeline_runs (
    run_id           BIGSERIAL    PRIMARY KEY,
    flow_run_id      TEXT,                                   -- identifiant Prefect (lien avec l'interface)
    started_at       TIMESTAMPTZ  NOT NULL,
    finished_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    status           TEXT         NOT NULL CHECK (status IN ('ok', 'échec')),
    days_added       INTEGER      NOT NULL DEFAULT 0,
    model_status     TEXT,
    forecast_status  TEXT,
    message          TEXT                                    -- résumé, ou l'erreur en cas d'échec
);
CREATE INDEX IF NOT EXISTS idx_pipeline_runs_finished ON ops.pipeline_runs (finished_at DESC);

